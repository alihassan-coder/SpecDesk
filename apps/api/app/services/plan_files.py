"""Downloadable files, generated from a saved plan version on request.

Files are derived data: the same version always gives the same bytes, so nothing is stored.
PDF comes later (needs a renderer); everything here is plain text plus a ZIP of it all.
"""

import csv
import io
import json
import re
import zipfile
from dataclasses import dataclass
from typing import Any, Literal

Json = dict[str, Any]
Kind = Literal["md", "csv", "json", "mmd", "zip"]

MEDIA_TYPES: dict[Kind, str] = {
    "md": "text/markdown; charset=utf-8",
    "csv": "text/csv; charset=utf-8",
    "json": "application/json",
    "mmd": "text/plain; charset=utf-8",
    "zip": "application/zip",
}


@dataclass(frozen=True)
class PlanFileOut:
    name: str
    kind: Kind
    content: bytes

    @property
    def media_type(self) -> str:
        return MEDIA_TYPES[self.kind]


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40] or "plan"


def build_files(plan: Json) -> list[PlanFileOut]:
    text_files = [
        PlanFileOut("spec.md", "md", spec_markdown(plan).encode()),
        PlanFileOut("backlog.csv", "csv", backlog_csv(plan).encode()),
        PlanFileOut("backlog.json", "json", backlog_json(plan).encode()),
        PlanFileOut("flow.mmd", "mmd", flow_mermaid(plan).encode()),
        PlanFileOut("build-prompt.md", "md", build_prompt(plan).encode()),
    ]
    return [*text_files, _zip(plan, text_files)]


def find_file(plan: Json, name: str) -> PlanFileOut | None:
    return next((f for f in build_files(plan) if f.name == name), None)


def human_size(n: int) -> str:
    return f"{n} B" if n < 1024 else f"{n / 1024:.1f} KB"


def preview(f: PlanFileOut, limit: int = 4000) -> str | None:
    if f.kind == "zip":
        return None
    text = f.content.decode()
    return text if len(text) <= limit else text[:limit] + "\n…"


# ---------- generators ----------


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {i}" for i in items) if items else "- None noted"


def _money(n: int, currency: str) -> str:
    return f"${n:,}" if currency == "USD" else f"{n:,} {currency}"


def spec_markdown(plan: Json) -> str:
    est: Json = plan.get("estimate", {})
    spec: Json = plan.get("spec", {})
    cur = str(est.get("currency", "USD"))
    lines = [
        f"# {plan['title']}",
        "",
        f"> {plan.get('oneLiner', '')}",
        "",
        "## Problem",
        plan.get("problem", ""),
        "",
        "## Users",
        _bullets(plan.get("audience", [])),
        "",
        "## Goals",
        _bullets(plan.get("goals", [])),
        "",
        "## Estimate",
        f"- Price: {_money(int(est.get('priceMin', 0)), cur)} – "
        f"{_money(int(est.get('priceMax', 0)), cur)}",
        f"- Timeline: {est.get('weeks', '?')} weeks ({est.get('hours', '?')} hours)",
        f"- Readiness: {plan.get('readiness', '?')}/100",
        "",
        "## Features",
    ]
    for group, title in (
        ("must", "Must have"),
        ("should", "Should have"),
        ("could", "Could have"),
        ("wont", "Later versions"),
    ):
        feats = [f for f in plan.get("features", []) if f["moscow"] == group]
        if not feats:
            continue
        lines += ["", f"### {title}"]
        for f in feats:
            size = f"{f['complexity']}, {f['hours']} h"
            lines.append(f"- **{f['name']}** ({size}) — {f['description']}")
            lines += [f"  - {s}" for s in f.get("stories", [])]
    lines += ["", "## Screens"]
    lines += [f"- **{s['name']}** — {s['purpose']}" for s in plan.get("screens", [])]
    lines += ["", "## Tech stack", "", "| Layer | Choice | Why | Alternative |"]
    lines.append("|---|---|---|---|")
    lines += [
        f"| {c['layer']} | {c['choice']} | {c['why']} | {c['alternative']} |"
        for c in plan.get("stack", [])
    ]
    lines += ["", "## Phases"]
    for p in plan.get("phases", []):
        lines.append(f"- **{p['name']}** ({p['weeks']} weeks): " + "; ".join(p["deliverables"]))
    lines += [
        "",
        "## Team",
        _bullets(plan.get("team", [])),
        "",
        "## Implementation decisions",
        _bullets(spec.get("implementationDecisions", [])),
        "",
        "## Testing decisions",
        _bullets(spec.get("testingDecisions", [])),
        "",
        "## Risks",
    ]
    lines += [
        f"- **{r['title']}** ({r['impact']}) — {r['mitigation']}" for r in plan.get("risks", [])
    ]
    lines += [
        "",
        "## Assumptions",
        _bullets(plan.get("assumptions", [])),
        "",
        "## Out of scope",
        _bullets(spec.get("outOfScope", [])),
        "",
        "---",
        "Generated by SpecDesk. Prices and weeks are estimates to discuss on a call.",
        "",
    ]
    return "\n".join(lines)


def backlog_csv(plan: Json) -> str:
    names = {f["id"]: f["name"] for f in plan.get("features", [])}
    out = io.StringIO()
    w = csv.writer(out)
    w.writerow(["ID", "Title", "Feature", "Description", "Acceptance criteria", "Blocked by"])
    for t in plan.get("backlog", []):
        w.writerow(
            [
                t["id"],
                t["title"],
                names.get(t["featureId"], t["featureId"]),
                t["description"],
                "\n".join(t["acceptance"]),
                ", ".join(t["blockedBy"]),
            ]
        )
    return out.getvalue()


def backlog_json(plan: Json) -> str:
    return json.dumps({"tickets": plan.get("backlog", [])}, ensure_ascii=False, indent=2) + "\n"


def flow_mermaid(plan: Json) -> str:
    screens = {s["id"]: s["name"] for s in plan.get("screens", [])}

    def node(sid: str) -> str:
        safe = re.sub(r"[^A-Za-z0-9_]", "_", sid) or "screen"
        label = screens.get(sid, sid).replace('"', "'")
        return f'{safe}["{label}"]'

    lines = ["flowchart LR"]
    for step in plan.get("flow", []):
        action = step["action"].replace('"', "'").replace("|", "/")
        lines.append(f'  {node(step["from"])} -->|"{action}"| {node(step["to"])}')
    if len(lines) == 1:
        lines += [f"  {node(sid)}" for sid in screens]
    return "\n".join(lines) + "\n"


def build_prompt(plan: Json) -> str:
    must = [f for f in plan.get("features", []) if f.get("included")]
    stack = "\n".join(f"- {c['layer']}: {c['choice']}" for c in plan.get("stack", []))
    tickets = "\n".join(
        f"{t['id']}. {t['title']}"
        + (f" (after {', '.join(t['blockedBy'])})" if t["blockedBy"] else "")
        for t in plan.get("backlog", [])
    )
    features = "\n".join(f"- {f['name']}: {f['description']}" for f in must)
    return f"""# Build prompt — {plan["title"]}

Paste this into Cursor, Claude Code or another coding agent to start the build.

You are building **{plan["title"]}**: {plan.get("oneLiner", "")}

## Problem
{plan.get("problem", "")}

## First-version features
{features}

## Stack
{stack}

## Work in this order
Build one ticket at a time as a thin end-to-end slice (UI, API, data, tests), and show it working
before starting the next. Full acceptance criteria are in backlog.csv.

{tickets}

## Rules
- Write tests for every ticket's acceptance criteria.
- Ask before adding anything not in this plan.
"""


def _zip(plan: Json, files: list[PlanFileOut]) -> PlanFileOut:
    buf = io.BytesIO()
    folder = f"specdesk-{slug(plan['title'])}"
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            # Fixed timestamp keeps the ZIP identical for the same plan.
            info = zipfile.ZipInfo(f"{folder}/{f.name}", date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, f.content)
    return PlanFileOut(f"{folder}.zip", "zip", buf.getvalue())
